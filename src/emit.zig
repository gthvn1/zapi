const std = @import("std");
const RawXapi = @import("RawXapi.zig");
const TypeParser = @import("TypeParser.zig");

fn findSelf(tp: *TypeParser, name: []const u8, params: []const RawXapi.MessageInfoParam) !?usize {
    // The rule to find a self parameter is:
    // 1. if a parameter is named "self" -> This is the one
    // 2. otherwise, the parameter type is the same as the class ref
    // 3. otherwise null
    for (params, 0..) |p, i| {
        if (std.mem.eql(u8, "self", p.name)) return i;
    }

    for (params, 0..) |p, i| {
        const p_ty = try tp.parse(p.type);
        if (p_ty == .ref and std.mem.eql(u8, name, p_ty.ref)) return i;
    }

    return null;
}

fn writeZigType(w: *std.Io.Writer, node: *const TypeParser.AstNode) !void {
    switch (node.*) {
        .string => try w.writeAll("[]const u8"),
        .int => try w.writeAll("i64"),
        .float => try w.writeAll("f64"),
        .bool => try w.writeAll("bool"),
        .datetime => return error.DateTimeNotSupported,
        .void => try w.writeAll("void"),
        .ref => |str| {
            const cn = ClassName{ .raw = str };
            try w.print("{f}", .{cn});
        },
        .record => return error.RecordNotSupported,
        .set => |sub_node| {
            try w.writeAll("[]");
            try writeZigType(w, sub_node);
        },
        .option => |sub_node| {
            try w.writeAll("?");
            try writeZigType(w, sub_node);
        },
        .map => return error.MapNotSupported,
        .@"enum" => return error.EnumNotSupported,
    }
}

fn genCode(tp: *TypeParser, ci: *const RawXapi.ClassInfo, methods: []const []const u8, w: *std.Io.Writer) !void {
    for (ci.messages) |m| {
        for (methods) |method| {
            if (!std.mem.eql(u8, m.name, method)) continue;

            try w.print("pub fn {s}(", .{m.name});

            // Params are ordered. We need to find if a parameter is the same type than
            // ClassInfo and put it first. Then conn and then others parameters.
            if (try findSelf(tp, ci.name, m.params)) |idx| {
                const ty = try tp.parse(m.params[idx].type);

                //try w.print("{s}:{s},", .{ m.params[idx].name, try Stub.zigType(m.params[idx].type) });
                try w.print("{s}:", .{m.params[idx].name});
                try writeZigType(w, &ty);
                try w.writeAll(",conn: *Conn,");
                for (m.params, 0..) |mip, i| {
                    if (i == idx) continue;
                    const mip_ty = try tp.parse(mip.type);
                    try w.print("{s}:", .{mip.name});
                    try writeZigType(w, &mip_ty);
                    try w.writeAll(",");
                }
            } else {
                try w.writeAll("conn: *Conn,");
                for (m.params) |mip| {
                    const mip_ty = try tp.parse(mip.type);
                    try w.print("{s}:", .{mip.name});
                    try writeZigType(w, &mip_ty);
                    try w.writeAll(",");
                }
            }

            const res_ty = try tp.parse(m.result);

            try w.writeAll(") !"); // All functions can fail, so always add !
            try writeZigType(w, &res_ty);
            try w.writeAll("{\n");

            // BODY
            // 1. declare params
            try w.print("const params: [{d}][]const u8 = .{{", .{m.params.len});
            for (m.params) |mip| {
                const mip_ty = try tp.parse(mip.type);
                if (mip_ty == .ref) {
                    try w.print("{s}.ref,", .{mip.name});
                } else {
                    try w.print("{s},", .{mip.name});
                }
            }
            try w.writeAll("};\n");
            // 2. rpc
            try w.print(
                "const body = try rpc.writeRequest(conn.allocator, \"{s}.{s}\", &params, 1);\n",
                .{ ci.name, m.name },
            );
            // 3. free things
            try w.writeAll("defer conn.allocator.free(body);\n");
            // 4. and the call
            try w.writeAll("return rpc.call(conn, ");
            try writeZigType(w, &res_ty);
            try w.writeAll(", body);\n");

            try w.writeAll("}\n");
        }
    }
}

pub fn xapi_bindings(a: std.mem.Allocator, w: *std.Io.Writer, rapi: *const RawXapi) !void {
    var draft: std.Io.Writer.Allocating = .init(a);
    defer draft.deinit();
    const out = &draft.writer;

    var tp = TypeParser.init(a);
    defer tp.deinit();

    // First we generate the header comment
    try out.writeAll("// This file is automatically generated\n");
    try out.print("const rpc = struct {{ {s} }};\n", .{@embedFile("rpc.zig")});
    try out.writeAll("// We want Conn to be visible from client, so we need to reexport it\n");
    try out.writeAll("pub const Conn = rpc.Connection;\n");

    // Starting struct Class
    try out.writeAll("pub const Class = struct {\n");

    for (rapi.root.items) |*class_info| {
        const class_name: ClassName = .{ .raw = class_info.name };
        try out.print("pub const {f} = struct {{\n", .{class_name});
        // Only object classes (see hasRef) get a ref
        if (class_info.hasRef()) {
            try out.writeAll("ref: []const u8,\n");
            try out.print("pub const jsonParseFromValue = rpc.OpaqueRef({f}).jsonParseFromValue;\n", .{class_name});
        }

        // TODO: Currently we want to generate the four methods used by basic.zig.
        //       Remove the filter when everything is generated automatically.
        if (std.mem.eql(u8, "session", class_info.name)) {
            try genCode(&tp, class_info, &[_][]const u8{ "login_with_password", "logout" }, out);
        }

        if (std.mem.eql(u8, "VM", class_info.name)) {
            try genCode(&tp, class_info, &[_][]const u8{ "get_all", "get_name_label" }, out);
        }

        try out.writeAll("};\n");
    }

    // End of pub const class
    try out.writeAll("};\n");

    // Now we can format "out" and print it in the writer.
    const source = try draft.toOwnedSliceSentinel(0);
    defer draft.allocator.free(source);

    var ast = try std.zig.Ast.parse(a, source, .zig);
    defer ast.deinit(a);

    if (ast.errors.len > 0) {
        try w.writeAll(source);
        for (ast.errors) |e| {
            const loc = ast.tokenLocation(0, e.token);
            var buf: [256]u8 = undefined;
            var msg: std.Io.Writer = .fixed(&buf);
            try ast.renderError(e, &msg);
            std.log.err("generated code {d}:{d}: {s}", .{ loc.line + 1, loc.column + 1, msg.buffered() });
        }
        return error.InvalidGeneratedCode;
    }

    return ast.render(a, w, .{});
}

const ClassName = struct {
    raw: []const u8,

    // ClassName is small so we can pass it by value
    pub fn format(self: ClassName, w: *std.Io.Writer) std.Io.Writer.Error!void {
        var it = std.mem.splitScalar(u8, self.raw, '_');
        while (it.next()) |s| {
            if (s.len == 0) continue;
            try w.writeByte(std.ascii.toUpper(s[0]));
            for (s[1..]) |c| {
                try w.writeByte(std.ascii.toLower(c));
            }
        }
    }
};

// Helper for tests
fn expectClassName(expected: []const u8, input: []const u8) !void {
    var buf: [64]u8 = undefined;
    var w: std.Io.Writer = .fixed(&buf);
    try w.print("{f}", .{ClassName{ .raw = input }});
    try std.testing.expectEqualStrings(expected, w.buffered());
}

test "class name conversion" {
    try expectClassName("Session", "session");
    try expectClassName("Vm", "VM");
    try expectClassName("VmGroup", "VM_group");
    try expectClassName("Vmpp", "VMPP");
    try expectClassName("SrStat", "sr_stat");
    try expectClassName("ClusterHost", "Cluster_host");
    try expectClassName("VdiNbdServerInfo", "vdi_nbd_server_info");
    // tricky cases not found in xenapi.json
    try expectClassName("AB", "a__b");
    try expectClassName("B", "b_");
    try expectClassName("B", "_b");
}
